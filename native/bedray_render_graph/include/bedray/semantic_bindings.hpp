#pragma once

#include "bedray/render_graph.hpp"

#include <cstdint>
#include <string>
#include <vector>

namespace bedray::graph {

// These are semantic categories, not VkDescriptorType numeric values. The
// later Vulkan adapter maps them only after reflection has been validated.
enum class BindingKind : std::uint8_t {
    uniform_buffer,
    storage_buffer,
    sampled_image,
    storage_image,
    combined_image_sampler,
    acceleration_structure,
};

struct ReflectedBinding {
    std::string shader_name;
    std::string semantic;
    std::uint32_t set;
    std::uint32_t binding;
    std::uint32_t count;
    BindingKind kind;
};

struct ResolvedBinding {
    std::uint32_t set;
    std::uint32_t binding;
    BindingKind kind;
    ResourceId resource;
};

enum class BindingErrorCode : std::uint8_t {
    none,
    invalid_name,
    duplicate_binding,
    duplicate_shader_name,
    duplicate_semantic,
    unsupported_set,
    unsupported_array,
    invalid_pass,
    undeclared_resource,
    kind_mismatch,
    incompatible_access,
    incompatible_stage,
};

struct BindingError {
    BindingErrorCode code = BindingErrorCode::none;
    std::uint32_t binding = 0;
    std::string semantic;
};

// The input must be generated by a build-time reflection adapter. This routine
// does not parse SPIR-V or trust a manifest as proof of actual driver support.
// ABI v2 supports one set and one descriptor per binding. It is explicit here
// so unsupported layouts fail before creating any Vulkan object. `out` is left
// unchanged on validation failure.
[[nodiscard]] bool resolve_bindings(const RenderGraph& graph, PassId pass,
                                    const std::vector<ReflectedBinding>& reflected,
                                    std::vector<ResolvedBinding>& out, BindingError& error);

} // namespace bedray::graph
